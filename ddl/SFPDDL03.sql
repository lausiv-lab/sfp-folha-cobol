--=================================================================
-- VIEW: FOLHA ANALITICA COM DADOS DO EMPREGADO E DO EVENTO
--=================================================================
CREATE VIEW SFPADM.VW_FOLHA_ANALITICA AS
    SELECT F.COMPETENCIA,
           F.TIPO_FOLHA,
           F.MATRICULA,
           E.NOME,
           E.CENTRO_CUSTO,
           F.COD_EVENTO,
           F.DESCRICAO,
           F.NATUREZA,
           F.REFERENCIA,
           F.VALOR,
           V.CONTA_CONTABIL,
           V.INC_INSS,
           V.INC_IRRF,
           V.INC_FGTS
      FROM SFPADM.TB_FOLHA_CALC F
      JOIN SFPADM.TB_EMPREGADO  E ON E.MATRICULA  = F.MATRICULA
      JOIN SFPADM.TB_EVENTO     V ON V.COD_EVENTO = F.COD_EVENTO;

--=================================================================
-- VIEW: CUSTO TOTAL DE FOLHA POR CENTRO DE CUSTO
--=================================================================
CREATE VIEW SFPADM.VW_CUSTO_CENTRO AS
    SELECT R.COMPETENCIA,
           R.CENTRO_CUSTO,
           COUNT(*)                AS QTD_EMPREGADOS,
           SUM(R.TOT_PROVENTOS)    AS TOT_PROVENTOS,
           SUM(R.TOT_DESCONTOS)    AS TOT_DESCONTOS,
           SUM(R.LIQUIDO)          AS TOT_LIQUIDO,
           SUM(R.VLR_INSS)         AS TOT_INSS,
           SUM(R.VLR_IRRF)         AS TOT_IRRF,
           SUM(R.VLR_FGTS)         AS TOT_FGTS,
           SUM(R.TOT_PROVENTOS) + SUM(R.VLR_FGTS)
                                   AS CUSTO_EMPRESA
      FROM SFPADM.TB_FOLHA_RESUMO R
     GROUP BY R.COMPETENCIA, R.CENTRO_CUSTO;

--=================================================================
-- VIEW: EMPREGADOS ATIVOS COM DEPENDENTES DE IRRF
--=================================================================
CREATE VIEW SFPADM.VW_EMPREGADO_ATIVO AS
    SELECT E.MATRICULA,
           E.NOME,
           E.CPF,
           E.CENTRO_CUSTO,
           E.SALARIO_BASE,
           E.TIPO_SALARIO,
           (SELECT COUNT(*)
              FROM SFPADM.TB_DEPENDENTE D
             WHERE D.MATRICULA = E.MATRICULA
               AND D.IND_IRRF  = 'S')  AS QTD_DEP_IRRF_REAL
      FROM SFPADM.TB_EMPREGADO E
     WHERE E.SITUACAO IN ('A','F','L');

